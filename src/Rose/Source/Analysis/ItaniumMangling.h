#ifndef ROSE_Source_Analysis_ItaniumMangling_H
#define ROSE_Source_Analysis_ItaniumMangling_H 1

#include <RoseFirst.h>
#include <string>
#include <boost/utility/string_view.hpp>

namespace Rose::Source::Analysis
{
  /// Experimental Itanium C++ ABI name mangling API.
  ///    https://itanium-cxx-abi.github.io/cxx-abi/abi.html
  ///
  /// For entities with an ABI-visible C++ symbol, this API aims to produce an
  /// Itanium-compatible spelling.  It is also a ROSE analysis API, however,
  /// and therefore gives stable names to AST entities for which the ABI does
  /// not define standalone linker symbols (for example, parameters, local
  /// entities, and declaration nodes).  Those ROSE-only identities use the
  /// reserved _R extension namespace, and internal-linkage entities may
  /// include source-file information so they remain distinct across the
  /// translation units in a ROSE project.
  ///
  /// Consequently, a returned name is not universally a linker name: callers
  /// that need a compiler or linker ABI spelling should use this API only for
  /// supported ABI-visible entities and avoid ROSE extension spellings.  This
  /// note describes the intended boundary, rather than an exhaustive list of
  /// differences from the Itanium C++ ABI.  The API is experimental and is
  /// not yet a replacement for ExternalMangling.

  /// Returns the Itanium local-linkage suffix for \p filename.
  std::string itaniumLocalLinkageSuffix(boost::string_view filename);

  /// Generates an Itanium-compatible or ROSE analysis identity for
  /// SgDeclarationStatements.
  /// \param  n              the SgDeclarationStatement for which the mangled name is generated.
  /// \param  withUniqueMain if true the main function is made unique (enables processing projects with
  ///                        multiple main functions).
  /// \return an ABI-compatible name where the ABI defines one; otherwise a
  ///         ROSE extension identity
  /// \throws a runtime error if a node is passed for which no direct name mangling exists.
  ///         examples include: SgFunctionParameterList, SgVariableDeclaration
  /// \details
  ///    the mangled name, as generated by these functions, resolves types to their respective
  ///    canonical representation following the Itanium naming standard.
  ///    e.g., the two foo's below have the same mangled name when they are declared in
  ///          different translation units. The standard ROSE name mangling generates
  ///          different mangled names due to the presence of a typedef/using declaration.
  /// \code
  /// // unit1.cc
  /// using XInt = int;
  /// void foo(XInt);
  /// // unit2.cc
  /// void foo(int);
  /// \endcode
  /// \{
  const std::string&
  itaniumName(const SgDeclarationStatement& n, bool withUniqueMain = false);

  const std::string&
  itaniumName(const SgDeclarationStatement* n, bool withUniqueMain = false);
  /// \}

  /// Generates an Itanium-compatible type encoding for SgType nodes.
  /// \param  n              the SgType for which the mangled name is generated.
  /// \param  withReturnType if true, the return type of a function type is included in the mangled name.
  /// \param  withArrayToPointerDecay if true arrays are mangled as pointers
  /// \return a mangled name
  /// \details
  ///    withReturnType and withArrayToPointerDecay provide context for the name mangling.
  ///    e.g.,
  ///    * to mangle the type of f in int f (float nums[]); would require
  ///      withReturnType = false (return type not relevant)
  ///      withArrayToPointerDecay = true (nums will be mangled as pointer)
  ///    * to mangle the type of sum in int f (float (*sum)(float nums[])); would require
  ///      withReturnType = true (return type is relevant)
  ///      withArrayToPointerDecay = true (nums will be mangled as pointer)
  /// \{
  const std::string&
  itaniumName(const SgType& n, bool withReturnType=true, bool withArrayToPointerDecay=false);

  const std::string&
  itaniumName(const SgType* n, bool withReturnType=true, bool withArrayToPointerDecay=false);
  /// \}

  /// Generates an Itanium-compatible or ROSE analysis identity for
  /// SgInitializedName nodes.  Parameters use ROSE's reserved _R extension
  /// namespace so they remain stable, distinct analysis identities.  Data
  /// members use their class-qualified spelling.  Neither category has a
  /// standalone linker-symbol spelling in the Itanium ABI.
  /// \param  n              the initialized name for which the mangled name is generated.
  /// \return an ABI-compatible name where the ABI defines one; otherwise a
  ///         ROSE extension identity
  /// \{
  const std::string&
  itaniumName(const SgInitializedName& n);

  const std::string&
  itaniumName(const SgInitializedName* n);
  /// \}

  /// Clears the cache used by itaniumName.
  ///
  /// This invalidates all string references previously returned by itaniumName.
  void clearItaniumNameCache();
}

#endif /* ROSE_Source_Analysis_ItaniumMangling_H */
